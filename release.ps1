# Builds the portable release and writes latest.json next to it.
# The version comes from the app project, so the manifest can never disagree with the binary.

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
Set-Location $root

$dotnet = Join-Path $env:USERPROFILE '.dotnet10\dotnet.exe'
if (-not (Test-Path $dotnet)) { $dotnet = 'dotnet' }

[xml]$project = Get-Content 'src\SchoolPdfSorter.App\SchoolPdfSorter.App.csproj'
$version = @($project.Project.PropertyGroup.Version) | Where-Object { $_ } | Select-Object -First 1
if (-not $version) { throw 'No <Version> in SchoolPdfSorter.App.csproj.' }

if (Get-Process -Name SchoolPdfSorterApp -ErrorAction SilentlyContinue) {
    throw 'Close the running School PDF Sorter before publishing: the exe is locked.'
}

# Support details are scrambled and sealed exactly like the media sorter: XOR with a
# fixed key, then SHA-256 of the clear text. They come from support.local.json, which
# is never committed, so a public repository never carries the account numbers.
$supportSource = Join-Path $root 'support.local.json'
$supportGenerated = Join-Path $root 'src\SchoolPdfSorter.App\Support\support.g.cs'

if (Test-Path $supportSource) {
    $support = Get-Content $supportSource -Raw | ConvertFrom-Json

    $supportLines = @()
    foreach ($bank in $support.banks) {
        if ($bank.bank -and $bank.number) { $supportLines += "$($bank.bank)|$($bank.number)" }
    }
    if ($support.repo) { $supportLines += "repo|$($support.repo)" }
    if ($supportLines.Count -eq 0) { throw 'support.local.json has no bank rows.' }

    $supportClear = [System.Text.Encoding]::UTF8.GetBytes(($supportLines -join "`n"))
    $supportKey = [System.Text.Encoding]::UTF8.GetBytes('SchoolPdfSorter.support.v1')
    $supportScrambled = New-Object byte[] $supportClear.Length

    for ($i = 0; $i -lt $supportClear.Length; $i++) {
        $supportScrambled[$i] = $supportClear[$i] -bxor $supportKey[$i % $supportKey.Length]
    }

    $supportPayload = [Convert]::ToBase64String($supportScrambled)
    $supportSha = [System.Security.Cryptography.SHA256]::Create()
    $supportSeal = [Convert]::ToBase64String($supportSha.ComputeHash($supportClear))
    $supportSha.Dispose()

    $supportCode = @"
// <auto-generated />
// Written by release.ps1 from support.local.json. Never committed.
namespace SchoolPdfSorter.Support;

internal static partial class SupportPayload
{
    static partial void Fill(ref string payload, ref string seal)
    {
        payload = "$supportPayload";
        seal = "$supportSeal";
    }
}
"@

    [System.IO.File]::WriteAllText($supportGenerated, $supportCode, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Support details: $($support.banks.Count) bank row(s), sealed."
}
else {
    if (Test-Path $supportGenerated) { Remove-Item $supportGenerated -Force }
    Write-Host 'Support details: none, so the Support us button stays hidden.'
}

& $dotnet publish 'src\SchoolPdfSorter.App\SchoolPdfSorter.App.csproj' -c Release -r win-x64 `
    --self-contained true `
    -p:PublishSingleFile=true `
    -p:IncludeNativeLibrariesForSelfExtract=true `
    -p:EnableCompressionInSingleFile=true `
    -p:DebugType=None `
    -p:DebugSymbols=false `
    -o publish

if ($LASTEXITCODE -ne 0) { throw "publish failed with exit code $LASTEXITCODE" }

$exe = Join-Path $root 'publish\SchoolPdfSorterApp.exe'
$size = (Get-Item $exe).Length
$hash = (Get-FileHash -Algorithm SHA256 $exe).Hash.ToLowerInvariant()
$asset = "https://github.com/Tayo-Aina/SchoolPdfSorter/releases/download/v$version/SchoolPdfSorterApp.exe"

$manifest = [ordered]@{
    version = $version
    url     = $asset
    size    = $size
    sha256  = $hash
    notes   = ''
} | ConvertTo-Json

# No BOM: the updater parses this file as JSON, and a BOM is not part of JSON.
$manifestPath = Join-Path $root 'latest.json'
[System.IO.File]::WriteAllText($manifestPath, $manifest, [System.Text.UTF8Encoding]::new($false))

Write-Host ''
Write-Host "Published $version  ($([math]::Round($size / 1MB, 1)) MB)"
Write-Host "SHA-256  $hash"
Write-Host ''
Write-Host 'Next:'
Write-Host "  1. Upload publish\SchoolPdfSorterApp.exe to GitHub release v$version"
Write-Host "  2. git add latest.json && git commit -m \"Release $version\" && git push"
Write-Host ''
